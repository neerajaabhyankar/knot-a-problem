// The standard diagram of the Borromean rings: three circles in Venn position,
// each passing over one neighbour and under the other, cyclically.
//
// This one is drawn in the plane rather than projected from space, and for a
// reason worth stating: by Freedman-Skora no three ROUND circles in space form
// the Borromean rings, so there is no spatial configuration of circles to
// project. A diagram, however, is a planar object, and the picture below is the
// standard one. Over and under are assigned by the cyclic rule, not read off a
// height, and the breaks are computed from the crossings exactly as elsewhere.
import { writeFileSync } from 'node:fs';

const N = 240, R = 1.0, D = 0.56;
const circle = (k) => {
  const a = (k * 2 * Math.PI) / 3 + Math.PI / 2;
  const cx = D * Math.cos(a), cy = D * Math.sin(a);
  return Array.from({ length: N }, (_, i) => {
    const t = (i / N) * 2 * Math.PI;
    return [cx + R * Math.cos(t), cy + R * Math.sin(t)];
  });
};
const rings = [0, 1, 2].map(circle);

/** ring i passes OVER ring j exactly when j is the next one round. */
const isOver = (i, j) => (j - i + 3) % 3 === 1;

const segs = [];
rings.forEach((pts, ci) => {
  for (let i = 0; i < pts.length; i++) segs.push({ ci, i, a: pts[i], b: pts[(i + 1) % pts.length] });
});

const breaks = new Map();
for (let x = 0; x < segs.length; x++) for (let y = x + 1; y < segs.length; y++) {
  const S = segs[x], T = segs[y];
  if (S.ci === T.ci) continue;
  const r = [S.b[0]-S.a[0], S.b[1]-S.a[1]], s = [T.b[0]-T.a[0], T.b[1]-T.a[1]];
  const den = r[0]*s[1] - r[1]*s[0];
  if (Math.abs(den) < 1e-14) continue;
  const q = [T.a[0]-S.a[0], T.a[1]-S.a[1]];
  const t = (q[0]*s[1] - q[1]*s[0]) / den, u = (q[0]*r[1] - q[1]*r[0]) / den;
  if (t <= 0 || t >= 1 || u <= 0 || u >= 1) continue;
  const under = isOver(S.ci, T.ci) ? y : x;
  const param = under === x ? t : u;
  if (!breaks.has(under)) breaks.set(under, []);
  breaks.get(under).push(param);
}

const COLS = ['ringB','ringC','ringD'];
const SCALE = 1.45, LW = 1.9, GAP = 0.105;
const out = [];
segs.forEach((s, idx) => {
  const len = Math.hypot(s.b[0]-s.a[0], s.b[1]-s.a[1]) * SCALE;
  const half = Math.min(GAP / Math.max(len, 1e-9), 0.49);
  let pieces = [[0,1]];
  for (const t of (breaks.get(idx) ?? []).sort((a,b)=>a-b)) {
    const lo = t-half, hi = t+half;
    pieces = pieces.flatMap(([p,q]) => (hi<=p||lo>=q) ? [[p,q]]
      : [...(lo>p?[[p,Math.max(p,lo)]]:[]), ...(hi<q?[[Math.min(q,hi),q]]:[])]);
  }
  const P = (t) => [s.a[0]+(s.b[0]-s.a[0])*t, s.a[1]+(s.b[1]-s.a[1])*t];
  for (const [p,q] of pieces) {
    if (q-p < 1e-6) continue;
    const A = P(p), B = P(q), f = (v) => (v*SCALE).toFixed(4);
    out.push(`\\draw[${COLS[s.ci]},line width=${LW}pt,line cap=round] (${f(A[0])},${f(A[1])})--(${f(B[0])},${f(B[1])});`);
  }
});
writeFileSync('fig-borromean.tex',
  `% generated by make-borromean-figure.mjs -- do not edit\n\\begin{tikzpicture}\n${out.join('\n')}\n\\end{tikzpicture}\n`);
console.log(`fig-borromean.tex: ${[...breaks.values()].reduce((a,b)=>a+b.length,0)} breaks, ${out.length} pieces`);
