// The reference picture of the Borromean rings: three mutually perpendicular
// golden rectangles, which is the classical model. Verified against knotlib
// before it is drawn, so the figure cannot disagree with the definition.
import { writeFileSync } from 'node:fs';
import { idOf, REFERENCE } from '../lib.mjs';

const PHI = (1 + Math.sqrt(5)) / 2;
const rect = (f) => ({ points: [f(-PHI,-1), f(PHI,-1), f(PHI,1), f(-PHI,1)], closed: true });
const RINGS = [
  rect((s,t) => [0, s, t]),
  rect((s,t) => [t, 0, s]),
  rect((s,t) => [s, t, 0]),
];
const got = idOf(RINGS, 128);
console.log(`three golden rectangles: ${got.raw} crossings, reduce to ${got.n};  ` +
  (got.print === REFERENCE.borromean ? 'IS the Borromean rings' : 'NOT Borromean'));
if (got.print !== REFERENCE.borromean) process.exit(1);

const sub=(a,b)=>[a[0]-b[0],a[1]-b[1],a[2]-b[2]];
const cross=(a,b)=>[a[1]*b[2]-a[2]*b[1],a[2]*b[0]-a[0]*b[2],a[0]*b[1]-a[1]*b[0]];
const dot=(a,b)=>a[0]*b[0]+a[1]*b[1]+a[2]*b[2];
const unit=(a)=>{const m=Math.hypot(...a);return [a[0]/m,a[1]/m,a[2]/m];};
const w = unit([1,1,1]);
const u = unit(cross(Math.abs(w[0])<0.9?[1,0,0]:[0,1,0], w));
const v = cross(w,u);

const COLS = ['ringB','ringC','ringD'];
const chunks = [];
RINGS.forEach((r, ci) => {
  const pts = r.points, n = pts.length, per = 14, dense = [];
  for (let i=0;i<n;i++){ const a=pts[i], b=pts[(i+1)%n];
    for(let k=0;k<per;k++){const t=k/per; dense.push([a[0]+(b[0]-a[0])*t,a[1]+(b[1]-a[1])*t,a[2]+(b[2]-a[2])*t]);} }
  for (let i=0;i<dense.length;i++){
    const p=dense[i], q=dense[(i+1)%dense.length];
    chunks.push({ci, depth:(dot(p,w)+dot(q,w))/2,
      a:[dot(p,u)*0.95,dot(p,v)*0.95], b:[dot(q,u)*0.95,dot(q,v)*0.95]});
  }
});
chunks.sort((x,y)=>x.depth-y.depth);
const f=(x)=>x.toFixed(3);
writeFileSync('fig-borromean.tex',
  '% generated by make-borromean-figure.mjs -- do not edit\n\\begin{tikzpicture}\n' +
  chunks.map(c=>`\\draw[white,line width=3.4pt] (${f(c.a[0])},${f(c.a[1])})--(${f(c.b[0])},${f(c.b[1])});\n`+
    `\\draw[${COLS[c.ci]},line width=1.5pt,line cap=round] (${f(c.a[0])},${f(c.a[1])})--(${f(c.b[0])},${f(c.b[1])});`).join('\n') +
  '\n\\end{tikzpicture}\n');
console.log('wrote fig-borromean.tex,', chunks.length, 'chunks');
