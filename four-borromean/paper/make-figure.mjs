// Emit TikZ for a picture of the link, viewed down a chosen axis.
//
// Over/under is drawn the way it is drawn by hand: the strand behind is
// interrupted where the strand in front passes over it. Mechanically, the
// polygons are cut into short chunks, the chunks are sorted back to front, and
// each is stroked first in the page colour (making the gap) and then in its
// own. No crossing data is needed, and the result cannot disagree with the
// geometry because it IS the geometry.
import { readFileSync, writeFileSync } from 'node:fs';

const { rings } = JSON.parse(readFileSync('link.json', 'utf8'));
const COLS = ['ringA', 'ringB', 'ringC', 'ringD'];

const sub = (a,b) => [a[0]-b[0], a[1]-b[1], a[2]-b[2]];
const cross = (a,b) => [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]];
const dot = (a,b) => a[0]*b[0]+a[1]*b[1]+a[2]*b[2];
const unit = (a) => { const m = Math.hypot(...a); return [a[0]/m, a[1]/m, a[2]/m]; };

/** Orthonormal frame with w along the view direction. */
function frame(d) {
  const w = unit(d);
  const seed = Math.abs(w[0]) < 0.9 ? [1,0,0] : [0,1,0];
  const u = unit(cross(seed, w));
  return { u, v: cross(w, u), w };
}

function emit(dir, { per = 7, scale = 1.05, lw = 1.25, halo = 3.0, name } = {}) {
  const { u, v, w } = frame(dir);
  const chunks = [];
  rings.forEach((pts, ci) => {
    const n = pts.length;
    const dense = [];
    for (let i = 0; i < n; i++) {
      const a = pts[i], b = pts[(i+1) % n];
      for (let k = 0; k < per; k++) {
        const t = k / per;
        dense.push([a[0]+(b[0]-a[0])*t, a[1]+(b[1]-a[1])*t, a[2]+(b[2]-a[2])*t]);
      }
    }
    const m = dense.length;
    for (let i = 0; i < m; i++) {
      const p = dense[i], q = dense[(i+1) % m];
      chunks.push({
        ci,
        depth: (dot(p,w) + dot(q,w)) / 2,
        a: [dot(p,u)*scale, dot(p,v)*scale],
        b: [dot(q,u)*scale, dot(q,v)*scale],
      });
    }
  });
  chunks.sort((x,y) => x.depth - y.depth);          // back to front
  const f = (x) => x.toFixed(3);
  const body = chunks.map(c =>
    `\\draw[white,line width=${halo}pt] (${f(c.a[0])},${f(c.a[1])})--(${f(c.b[0])},${f(c.b[1])});\n` +
    `\\draw[${COLS[c.ci]},line width=${lw}pt,line cap=round] (${f(c.a[0])},${f(c.a[1])})--(${f(c.b[0])},${f(c.b[1])});`
  ).join('\n');
  writeFileSync(name, `% generated by make-figure.mjs -- do not edit\n\\begin{tikzpicture}\n${body}\n\\end{tikzpicture}\n`);
  console.log(`${name}: ${chunks.length} chunks, view down (${dir.join(',')})`);
}

emit([1,1,1],  { name: 'fig-link-3fold.tex' });
emit([0,0,1],  { name: 'fig-link-2fold.tex' });

