// One file for the page to load: both starting shapes per corner count.
//
// They answer different questions, and the page offers both because the
// trade-off is the interesting part:
//   clear (fewest-crossings.mjs) - hill-climbed to show the fewest crossings in
//                                  its best view, clearance held above 0.06.
//   roomy (best-gap.mjs)         - hill-climbed for the largest closest
//                                  approach knotlib can still confirm.
// Neither is "best" outright: the clear shapes are easier to read, the roomy
// ones easier to build, and each is worse than the other at the other thing.
//
// Both inputs are JSON, and neither is `starts.js`: reading the file this
// script writes, as an earlier version did, destroys the shapes the first time
// it runs twice.
import { readFileSync, writeFileSync } from 'node:fs';
import { fromArc, edgeClearance, selfEdgeClearance } from '../polygon.mjs';
import { clearest } from './fewest-crossings.mjs';

const gapOf = (c) => Math.min(edgeClearance(c), selfEdgeClearance(c));
const read = (f) => JSON.parse(readFileSync(new URL(f, import.meta.url), 'utf8'));
const clear = read('./fewest-crossings.json');
const roomy = read('./best-gap.json');

// Clearance has to be compared scale-free, or the bigger shape always wins:
// `gap / rms` is the measure both searches actually optimise against.
const ratioOf = (arc) => {
  const curves = fromArc(arc), pts = curves[0].points;
  const rms = Math.sqrt(pts.reduce((s, p) => s + p[0]**2 + p[1]**2 + p[2]**2, 0) / pts.length);
  return { rms, gap: gapOf(curves), ratio: gapOf(curves) / rms };
};
const r4 = (x) => Math.round(x * 1e4) / 1e4;

const OUT = {};
for (const k of Object.keys(clear)) {
  const c = clear[k], r = roomy[k];
  const cm = ratioOf(c.arc), rm = r && ratioOf(r.arc);
  // Every shape gets BOTH numbers, measured the same way: how busy its best
  // view is, and how many crossings each three-ring sublink still has after
  // knotlib simplifies it with R1 and R2.
  //
  // `roomy` is only offered where it is genuinely roomier than `clear`. The
  // crossings search breaks ties on clearance, so at several counts it lands
  // on a shape the clearance search never found, and a second button that is
  // worse at both things is noise.
  OUT[k] = {
    clear: { gap: c.gap, ratio: r4(cm.ratio), crossings: c.crossings, sublinkAfter: c.sublinkAfter, arc: c.arc },
    roomy: rm && rm.ratio > cm.ratio * 1.02
      ? { gap: r.gap, ratio: r4(rm.ratio), crossings: clearest(fromArc(r.arc)), sublinkAfter: r.sublinks, arc: r.arc }
      : null,
  };
}
writeFileSync(new URL('./starts.js', import.meta.url),
  `// Generated by bundle-starts.mjs -- do not edit by hand.\n` +
  `// Per corner count: the clearest shape found, and the roomiest.\n` +
  `window.STARTS = ${JSON.stringify(OUT)};\n`);

console.log('wrote starts.js');
console.log('corners | clear: gap  gap/rms  view  sublinks after R1/R2 | roomy: the same four');
for (const k of Object.keys(OUT)) {
  const c = OUT[k].clear, r = OUT[k].roomy;
  console.log(`${k.padStart(7)} | ${String(c.gap).padEnd(7)} ${String(c.ratio).padEnd(7)} ${String(c.crossings).padStart(4)}  ${c.sublinkAfter.padEnd(12)} | ` +
    (r ? `${String(r.gap).padEnd(7)} ${String(r.ratio).padEnd(7)} ${String(r.crossings).padStart(4)}  ${r.sublinkAfter}` : 'none roomier'));
}
