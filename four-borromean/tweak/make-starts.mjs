// Starting shapes for the tweaker: one knotlib-verified arc per corner count.
//
// WHY THIS IS NOT JUST `thinArc`. Thinning a ring to m corners MOVES the
// strand, so each count is its own link until checked (parent ReadMe §7), and
// the coarse ones come out too tight to play with — 6 corners thins to a gap of
// 0.038. So each count is (1) swept over its offsets and verified, then
// (2) widened by the parent's bounded-step optimiser, which cannot change the
// link type, in chunks, re-verifying after each one and keeping the last shape
// that still came back BORROMEAN.
//
// WHY THE CHUNKS, rather than widening all the way and checking once. Widening
// hard maximises gap and nothing else, and past a point it inflates the
// diagram: at 12 corners the unchunked run reaches a gap of 0.26 with sublinks
// projecting to 36 crossings, where the Kauffman bracket refuses (limit 16) and
// four fifths of directions are degenerate. The link is almost certainly still
// right — the step bound says so — but the certificate is gone, and a starting
// shape nobody can check is not worth 0.1 of clearance. Stopping at the last
// verified chunk keeps every shipped shape checkable.
//
// Writes `starts.js`, not `.json`, so index.html opens from file:// with no
// server. Nothing in the parent directory is written.
import { writeFileSync } from 'node:fs';
import { optimise } from '../optimise-polygon.mjs';
import { thinArc, fromArc, edgeClearance, selfEdgeClearance, edgeStats } from '../polygon.mjs';
import { checkSymmetry } from '../tetra.mjs';
import { idOf, REFERENCE, sublinks } from '../lib.mjs';
import { allLinking } from '../linking.mjs';

const r4 = (x) => Math.round(x * 1e4) / 1e4;
const gapOf = (curves) => Math.min(edgeClearance(curves), selfEdgeClearance(curves));

/** All four sublinks Borromean, all six linking numbers zero, symmetry exact. */
function verify(arc, samples = 96) {
  const curves = fromArc(arc);
  checkSymmetry(curves);
  const got = sublinks(curves).map((s) => idOf(s.curves, samples));
  return {
    curves,
    gap: gapOf(curves),
    ns: got.map((x) => (x.ok ? x.n : '-')).join('/'),
    ok: got.every((x) => x.ok && x.print === REFERENCE.borromean)
        && allLinking(curves).lk.every((x) => x.value === 0),
  };
}

const OUT = {};
console.log('corners  off    gap thinned -> widened   edges min/max  turn   sublinks     verdict');
for (let m = 2; m <= 8; m++) {
  // 1. the offsets that verify, best gap first.
  let best = null;
  for (let offset = 0; offset < Math.round(60 / m); offset++) {
    const arc = thinArc(m, offset);
    if (gapOf(fromArc(arc)) < 0.01) continue; // strands touch; not a link to check
    const v = verify(arc);
    if (v.ok && (!best || v.gap > best.v.gap)) best = { offset, arc, v };
  }
  if (!best) { console.log(`${String(3*m).padStart(7)}    -    no offset verifies`); continue; }

  // 2. widen in chunks, keeping the last shape that still verifies.
  let arc = best.arc, v = best.v;
  for (let chunk = 0; chunk < 8; chunk++) {
    const res = optimise(arc, { steps: 2500, seed: 7 + chunk });
    if (res.gap <= v.gap * 1.02) break;        // nothing more to win
    const got = verify(res.arc);
    if (!got.ok) break;                         // past the checkable range
    arc = res.arc; v = got;
  }

  const es = edgeStats(v.curves);
  console.log(`${String(3*m).padStart(7)}${String(best.offset).padStart(5)}` +
    `    ${best.v.gap.toFixed(4)} -> ${v.gap.toFixed(4)}` +
    `          ${es.min.toFixed(2)}/${es.max.toFixed(2)}   ${es.turnMax.toFixed(0).padStart(4)}   ` +
    `${v.ns.padEnd(12)} ALL FOUR BORROMEAN`);
  OUT[3 * m] = { gap: r4(v.gap), sublinks: v.ns, arc: arc.map((p) => p.map(r4)) };
}

writeFileSync(new URL('./starts.js', import.meta.url),
  `// Generated by make-starts.mjs -- do not edit by hand.\n` +
  `// One third of one ring per corner count, knotlib-verified as shipped.\n` +
  `window.STARTS = ${JSON.stringify(OUT, null, 1)};\n`);
console.log('\nwrote starts.js:', Object.keys(OUT).join(', '), 'corners per ring');
